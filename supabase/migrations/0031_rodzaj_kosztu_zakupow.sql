alter table public.zakupy add column rodzaj_kosztu text check (rodzaj_kosztu in ('materialy', 'kooperacja', 'transport_inne'));
alter table public.zakupy add column rodzaj_reczny boolean not null default false;
alter table public.zakupy add column klasyfikacja_powod text;
create index on public.zakupy (rodzaj_kosztu);

/**
 * Rodzaj kosztu pozycji zakupu: reguła (najwyższy priorytet, pasujący typ zamówienia), inaczej rozpoznanie z importu
 * (materiał / pomocnicze -> materiały, dopłata -> transport i inne, usługa z kategorią -> wg zakładki kategorii);
 * usługa bez rozpoznania -> null (bufor „Do klasyfikacji”).
 */
create function public.klasyfikuj_zakup(p_nazwa text, p_typ text, p_rodzaj text, p_kategoria_uslugi text, out rodzaj_kosztu text, out powod text)
language plpgsql stable security invoker set search_path = public as $$
declare
  r record;
  v_zakladka text;
begin
  select * into r from public.reguly_klasyfikacji
   where aktywna and (typ_zamowienia is null or typ_zamowienia = p_typ) and p_nazwa ~* wzorzec
   order by priorytet desc, id limit 1;
  if found then
    rodzaj_kosztu := r.rodzaj_kosztu; powod := 'reguła: ' || coalesce(r.opis, r.wzorzec); return;
  end if;
  if p_rodzaj in ('material', 'pomocnicze') then rodzaj_kosztu := 'materialy'; powod := p_typ || ' - materiał'; return; end if;
  if p_rodzaj = 'doplata' then rodzaj_kosztu := 'transport_inne'; powod := 'dopłata (atest, transport)'; return; end if;
  if p_kategoria_uslugi is not null then
    select zakladka into v_zakladka from public.kategorie_uslug where kod = p_kategoria_uslugi;
    rodzaj_kosztu := case when v_zakladka = 'kooperacja' then 'kooperacja' else 'transport_inne' end;
    powod := 'kategoria usługi: ' || p_kategoria_uslugi; return;
  end if;
  rodzaj_kosztu := null; powod := 'usługa bez rozpoznania - do klasyfikacji';
end $$;

/** Import i zmiana nazwy / typu: klasyfikacja automatyczna, chyba że człowiek zdecydował ręcznie. */
create function public.klasyfikuj_zakup_trg() returns trigger
language plpgsql set search_path = public as $$
declare k record;
begin
  if new.rodzaj_reczny then return new; end if;
  k := public.klasyfikuj_zakup(new.nazwa, new.typ_zamowienia, new.rodzaj, new.kategoria_uslugi);
  new.rodzaj_kosztu := k.rodzaj_kosztu; new.klasyfikacja_powod := k.powod;
  return new;
end $$;
create trigger trg_klasyfikacja before insert or update of nazwa, typ_zamowienia, rodzaj, kategoria_uslugi, rodzaj_reczny on public.zakupy
  for each row execute function public.klasyfikuj_zakup_trg();

/** „Przeklasyfikuj wszystko” po zmianie reguł - pozycje z ręczną decyzją zostają. Zwraca liczbę zmienionych. */
create function public.przeklasyfikuj_zakupy() returns integer
language plpgsql security invoker set search_path = public as $$
declare v integer;
begin
  if not public.moze_baze_cen() then raise exception 'Przeklasyfikowanie zakupów: brak uprawnień (dział handlowy, prezes, administrator).'; end if;
  with k as (
    select z.id, (public.klasyfikuj_zakup(z.nazwa, z.typ_zamowienia, z.rodzaj, z.kategoria_uslugi)).* from public.zakupy z where not z.rodzaj_reczny
  )
  update public.zakupy z set rodzaj_kosztu = k.rodzaj_kosztu, klasyfikacja_powod = k.powod
  from k where k.id = z.id and (z.rodzaj_kosztu is distinct from k.rodzaj_kosztu or z.klasyfikacja_powod is distinct from k.powod);
  get diagnostics v = row_count;
  return v;
end $$;
revoke execute on function public.przeklasyfikuj_zakupy(), public.klasyfikuj_zakup(text, text, text, text) from public, anon;
grant execute on function public.przeklasyfikuj_zakupy(), public.klasyfikuj_zakup(text, text, text, text) to authenticated, service_role;

