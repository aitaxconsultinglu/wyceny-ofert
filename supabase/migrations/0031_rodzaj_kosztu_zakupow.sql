-- Historyczny cennik (runda 2, faza 4.2): zakupy z kart dostawy Optimy w trzech rodzajach kosztu - materiały, kooperacja,
-- transport / badania / inne. Pierwszy sygnał to typ zamówienia (ZM materiał, ZJ usługa) i rozpoznanie z importu;
-- słowa kluczowe PL/EN w tabeli reguly_klasyfikacji rozstrzygają usługi (i usługi zamawiane jako ZM). Pozycje niepewne
-- (null) trafiają do bufora „Do klasyfikacji”. Decyzja człowieka (rodzaj_reczny) nie jest nadpisywana przez automat.
-- Ceny w wycenach (dobierzCene) biorą tylko „materiały”; kooperacja i transport / badania - tylko z ofert pod zapytanie.

create function public.regex_poprawny(p text) returns boolean
language plpgsql immutable as $$
begin
  perform '' ~* p;
  return true;
exception when others then
  return false;
end $$;

create table public.reguly_klasyfikacji (
  id              bigint generated by default as identity primary key,
  wzorzec         text not null check (public.regex_poprawny(wzorzec)),   -- wyrażenie regularne (bez rozróżniania wielkości liter)
  rodzaj_kosztu   text not null check (rodzaj_kosztu in ('materialy', 'kooperacja', 'transport_inne')),
  typ_zamowienia  text check (typ_zamowienia in ('ZM', 'ZJ')),            -- null = każdy typ
  priorytet       integer not null default 0,                              -- wyższy wygrywa
  opis            text,
  aktywna         boolean not null default true,
  zmodyfikowano   timestamptz not null default now()
);
create trigger trg_zmodyfikowano before update on public.reguly_klasyfikacji for each row execute function public.dotknij_rekord();
create trigger trg_audyt after insert or update or delete on public.reguly_klasyfikacji for each row execute function public.audytuj('-');
alter table public.reguly_klasyfikacji enable row level security;
create policy rk_select on public.reguly_klasyfikacji for select to authenticated using (public.jest_pracownikiem());
create policy rk_write on public.reguly_klasyfikacji for all to authenticated using (public.moze_baze_cen()) with check (public.moze_baze_cen());

