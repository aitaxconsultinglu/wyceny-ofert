-- Historyczny cennik (runda 2, faza 4.1): cennik roboczogodzin - stanowiska × przedziały czasu pracy albo stawka stała,
-- z wersjami (wazna_od) i historią w audycie. Stawki są poufne: czytają je prezes, administrator i konta z flagą
-- „widzi narzuty i marże”; zmieniają prezes i administrator. Nowa wycena dostaje migawkę stawek (funkcja security
-- definer), więc liczenie wyceny działa bez flagi, a zmiana cennika nie zmienia istniejących wycen.
-- Wartości stawek NIE są w repozytorium - wczytuje je lokalnie `npm run seed:stawki` z pliku prywatne/ albo administrator.

create table public.przedzialy_czasu (
  kod            text primary key,
  nazwa          text not null,
  nazwa_en       text,
  kolejnosc      integer not null default 0,
  aktywny        boolean not null default true,
  zmodyfikowano  timestamptz not null default now()
);
create trigger trg_zmodyfikowano before update on public.przedzialy_czasu for each row execute function public.dotknij_rekord();
create trigger trg_audyt after insert or update or delete on public.przedzialy_czasu for each row execute function public.audytuj('-');
alter table public.przedzialy_czasu enable row level security;
create policy pcz_select on public.przedzialy_czasu for select to authenticated using (public.jest_pracownikiem());
create policy pcz_write on public.przedzialy_czasu for all to authenticated
  using (public.jest_administratorem()) with check (public.jest_administratorem());
insert into public.przedzialy_czasu (kod, nazwa, nazwa_en, kolejnosc) values
  ('7-15', '7:00-15:00', '7:00-15:00', 1), ('15-19', '15:00-19:00', '15:00-19:00', 2),
  ('19-7', '19:00-7:00', '19:00-7:00', 3), ('wolne', 'dni wolne', 'days off', 4);

create table public.cennik_robocizny (
  id              bigint generated by default as identity primary key,
  nazwa           text not null,
  nazwa_en        text,
  tryb            text not null default 'przedzialy' check (tryb in ('przedzialy', 'stala')),
  mpk_kod         text references public.mpk(kod),
  srednia         boolean not null default false,   -- stawka średnia warsztatu (metoda wskaźnikowa)
  do_weryfikacji  boolean not null default false,
  aktywne         boolean not null default true,
  kolejnosc       integer not null default 0,
  uwagi           text,
  zmodyfikowano   timestamptz not null default now()
);
create unique index cennik_robocizny_nazwa on public.cennik_robocizny (lower(nazwa)) where aktywne;
create trigger trg_zmodyfikowano before update on public.cennik_robocizny for each row execute function public.dotknij_rekord();
create trigger trg_audyt after insert or update or delete on public.cennik_robocizny for each row execute function public.audytuj('-');
alter table public.cennik_robocizny enable row level security;
-- Nazwy stanowisk widzi każdy pracownik (lista w wycenie); stawki - osobna tabela.
create policy cr_select on public.cennik_robocizny for select to authenticated using (public.jest_pracownikiem());
create policy cr_write on public.cennik_robocizny for all to authenticated
  using (public.ma_role('prezes', 'administrator')) with check (public.ma_role('prezes', 'administrator'));

create table public.cennik_robocizny_stawki (
  id             bigint generated by default as identity primary key,
  stanowisko_id  bigint not null references public.cennik_robocizny(id) on delete cascade,
  przedzial_kod  text references public.przedzialy_czasu(kod) on update cascade,   -- null = stawka stała
  stawka         numeric(10,2) not null check (stawka >= 0),
  wazna_od       date not null default current_date,
  zmodyfikowano  timestamptz not null default now()
);
create unique index cennik_stawki_wersja on public.cennik_robocizny_stawki (stanowisko_id, coalesce(przedzial_kod, ''), wazna_od);
create trigger trg_zmodyfikowano before update on public.cennik_robocizny_stawki for each row execute function public.dotknij_rekord();
create trigger trg_audyt after insert or update or delete on public.cennik_robocizny_stawki for each row execute function public.audytuj('-');
alter table public.cennik_robocizny_stawki enable row level security;
create policy crs_select on public.cennik_robocizny_stawki for select to authenticated using (public.widzi_marze());
create policy crs_write on public.cennik_robocizny_stawki for all to authenticated
  using (public.ma_role('prezes', 'administrator')) with check (public.ma_role('prezes', 'administrator'));

/** Stawki obowiązujące w dniu (najnowsza wersja nie późniejsza niż dzień) - dla osób z prawem do stawek (RLS). */
create or replace function public.stawki_cennika(p_dzien date default current_date)
returns table (stanowisko_id bigint, nazwa text, tryb text, przedzial_kod text, stawka numeric, wazna_od date, srednia boolean, mpk_kod text)
language sql stable security invoker set search_path = public as $$
  select distinct on (s.stanowisko_id, coalesce(s.przedzial_kod, ''))
         s.stanowisko_id, c.nazwa, c.tryb, s.przedzial_kod, s.stawka, s.wazna_od, c.srednia, c.mpk_kod
  from public.cennik_robocizny_stawki s join public.cennik_robocizny c on c.id = s.stanowisko_id
  -- Tylko stawki zgodne z trybem stanowiska (po zmianie trybu dawne wersje zostają w historii).
  where c.aktywne and s.wazna_od <= p_dzien and (c.tryb = 'stala') = (s.przedzial_kod is null)
  order by s.stanowisko_id, coalesce(s.przedzial_kod, ''), s.wazna_od desc;
$$;

/** Migawka cennika (wszystkie stanowiska i przedziały) - zapisywana w wycenie; czyta ją każdy, kto widzi wycenę. */
create function public._migawka_cennika() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('stanowisko_id', x.stanowisko_id, 'nazwa', x.nazwa, 'tryb', x.tryb, 'przedzial', x.przedzial_kod,
                                                'stawka', x.stawka, 'srednia', x.srednia, 'mpk', x.mpk_kod) order by c.kolejnosc, x.nazwa, x.przedzial_kod), '[]'::jsonb)
  from public.stawki_cennika(current_date) x join public.cennik_robocizny c on c.id = x.stanowisko_id;
$$;
revoke execute on function public._migawka_cennika() from public, anon, authenticated;

alter table public.wyceny add column stawki_cennika jsonb;
alter table public.wyceny add column stawki_cennika_data timestamptz;

/** Nowa wycena (i kopia) dostaje migawkę stawek z chwili utworzenia. */
create function public.migawka_stawek_wyceny() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.stawki_cennika is null then
    new.stawki_cennika := public._migawka_cennika();
    new.stawki_cennika_data := now();
  end if;
  return new;
end $$;
create trigger trg_migawka_stawek before insert on public.wyceny for each row execute function public.migawka_stawek_wyceny();

/** „Odśwież stawki z cennika” w wycenie (wersja edytowalna) - nowa migawka; pozycje zmienia klient. */
create function public.odswiez_stawki_wyceny(p_wycena uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v jsonb;
begin
  if not public.moze_edytowac_wycene(p_wycena) then raise exception 'Wycena zatwierdzona albo brak uprawnień - stawek nie można odświeżyć.'; end if;
  v := public._migawka_cennika();
  update public.wyceny set stawki_cennika = v, stawki_cennika_data = now() where id = p_wycena;
  return v;
end $$;

/** Czy cennik zmienił się od migawki wyceny (komunikat „cennik zmienił się od utworzenia wyceny”). */
create function public.cennik_zmieniony(p_wycena uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select max(greatest(s.zmodyfikowano, c.zmodyfikowano)) from public.cennik_robocizny_stawki s
                   join public.cennik_robocizny c on c.id = s.stanowisko_id)
                  > (select coalesce(w.stawki_cennika_data, '-infinity') from public.wyceny w where w.id = p_wycena and public.jest_pracownikiem()), false);
$$;
revoke execute on function public.odswiez_stawki_wyceny(uuid), public.cennik_zmieniony(uuid), public.stawki_cennika(date) from public, anon;
grant execute on function public.odswiez_stawki_wyceny(uuid), public.cennik_zmieniony(uuid), public.stawki_cennika(date) to authenticated;

-- Dotychczasowe stawki robocizny -> cennik (stawka stała, bez utraty wpisów). Stare pozycje wycen mają swoje stawki
-- zapisane w pozycji (migawka), więc nic się w nich nie zmienia; słownik stawki_robocizny zostaje.
insert into public.cennik_robocizny (nazwa, tryb, mpk_kod, srednia, do_weryfikacji, aktywne, kolejnosc, uwagi)
select s.rodzaj_pracy, 'stala', s.mpk_kod, s.domyslna, s.do_weryfikacji, s.aktywna, s.kolejnosc, s.uwagi
from public.stawki_robocizny s
where not exists (select 1 from public.cennik_robocizny c where lower(c.nazwa) = lower(s.rodzaj_pracy));
insert into public.cennik_robocizny_stawki (stanowisko_id, przedzial_kod, stawka, wazna_od)
select c.id, null, s.stawka, s.wazna_od
from public.stawki_robocizny s join public.cennik_robocizny c on lower(c.nazwa) = lower(s.rodzaj_pracy);
