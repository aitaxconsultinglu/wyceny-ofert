-- Rysunki i listy materiałowe (runda 2, faza 6): rodzaje tabel do zaznaczania zależne od rodzaju aparatu zapytania,
-- własne tabele (nazwa i kolumny w odczycie) i nazwa / rodzaj tabeli zapisane w odczycie (lista z filtrem i sortowaniem).
-- `struktura` mówi, jak odczyt jest układany i przenoszony do wyceny: czesci -> wykaz części (zakładka Materiały),
-- krocce -> tabela króćców (rury króćców i kołnierze), parametry -> dane projektowe (parametry projektu),
-- tabliczka -> dane identyfikacyjne, uwagi -> uwagi do wyceny, wlasna -> dowolne kolumny.

create table public.rodzaje_tabel (
  id               bigint generated by default as identity primary key,
  rodzaj_aparatu   text not null check (rodzaj_aparatu in ('zbiornik', 'wymiennik')),
  kod              text not null,
  nazwa            text not null,
  nazwa_en         text,
  struktura        text not null check (struktura in ('czesci', 'krocce', 'parametry', 'tabliczka', 'uwagi', 'wlasna')),
  kolumny          jsonb not null default '[]',      -- domyślne kolumny (własne tabele, podpowiedź dla AI)
  element_szablonu text,                             -- kod elementu szablonu (szablony.ts), do którego trafiają pozycje
  do_materialow    boolean not null default false,   -- pozycje przenoszone do zakładki Materiały
  kolejnosc        integer not null default 0,
  aktywny          boolean not null default true,
  zmodyfikowano    timestamptz not null default now(),
  unique (rodzaj_aparatu, kod)
);
create trigger trg_zmodyfikowano before update on public.rodzaje_tabel
  for each row execute function public.dotknij_rekord();
create trigger trg_audyt after insert or update or delete on public.rodzaje_tabel
  for each row execute function public.audytuj('-');

alter table public.rodzaje_tabel enable row level security;
create policy rtab_select on public.rodzaje_tabel for select to authenticated using (public.jest_pracownikiem());
create policy rtab_write on public.rodzaje_tabel for all to authenticated
  using (public.jest_administratorem()) with check (public.jest_administratorem());

