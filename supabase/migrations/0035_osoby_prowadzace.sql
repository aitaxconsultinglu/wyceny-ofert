-- Osoba prowadząca zapytanie wpisywana dowolnie (nie tylko konto aplikacji) i zapamiętywana na liście podpowiedzi.
create table public.osoby_prowadzace (
  id            bigint generated by default as identity primary key,
  nazwa         text not null unique check (length(trim(nazwa)) > 0),
  aktywny       boolean not null default true,
  utworzono     timestamptz not null default now(),
  zmodyfikowano timestamptz not null default now()
);
create trigger trg_zmodyfikowano before update on public.osoby_prowadzace
  for each row execute function public.dotknij_rekord();
create trigger trg_audyt after insert or update or delete on public.osoby_prowadzace
  for each row execute function public.audytuj('-');
alter table public.osoby_prowadzace enable row level security;
create policy op_select on public.osoby_prowadzace for select to authenticated using (public.jest_pracownikiem());
create policy op_insert on public.osoby_prowadzace for insert to authenticated with check (public.jest_pracownikiem());
create policy op_zmiana on public.osoby_prowadzace for update to authenticated using (public.jest_administratorem()) with check (public.jest_administratorem());
create policy op_usun on public.osoby_prowadzace for delete to authenticated using (public.jest_administratorem());

alter table public.zapytania add column prowadzacy_nazwa text;
-- Dotychczasowa osoba prowadząca (konto) - jej nazwa jako wpis tekstowy i na liście podpowiedzi.
update public.zapytania z set prowadzacy_nazwa = p.nazwa from public.profiles p where p.id = z.prowadzacy and z.prowadzacy_nazwa is null;
insert into public.osoby_prowadzace (nazwa)
  select distinct prowadzacy_nazwa from public.zapytania where prowadzacy_nazwa is not null on conflict (nazwa) do nothing;
